// Generates src/file-icons.generated.ts from the material-icon-theme package:
// the file-name / extension mapping plus the SVG bodies those mappings reach.
// Keeping it generated means the runtime stays dependency-free and only the
// icons the mapping can produce are bundled.
// Run: npm run generate:icons (also runs before dev and build).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const OUT = join(import.meta.dirname, "..", "src", "file-icons.generated.ts");

/** Walk up from the package entry to the directory holding its package.json. */
function packageRoot(entry) {
  let dir = dirname(entry);
  for (;;) {
    const file = join(dir, "package.json");
    if (existsSync(file) && JSON.parse(readFileSync(file, "utf8")).name === "material-icon-theme") return dir;
    const parent = dirname(dir);
    if (parent === dir) throw new Error("material-icon-theme package root not found");
    dir = parent;
  }
}

const root = packageRoot(require.resolve("material-icon-theme"));
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const manifest = JSON.parse(readFileSync(join(root, "dist", "material-icons.json"), "utf8"));

/** Lowercased keys; the panel matches on lowercased file names. */
function lowerKeys(map) {
  const out = {};
  for (const [key, value] of Object.entries(map)) {
    const lower = key.toLowerCase();
    if (lower === "" || lower.includes("/")) continue;
    if (out[lower] === undefined) out[lower] = value;
  }
  return out;
}

const extensions = lowerKeys(manifest.fileExtensions);
const names = lowerKeys(manifest.fileNames);
// The manifest's "light" block points bright icons at a darker variant; the
// web UI ships both and picks per theme, like VS Code does.
const lightExtensions = lowerKeys(manifest.light.fileExtensions);
const lightNames = lowerKeys(manifest.light.fileNames);
const used = new Set([
  manifest.file,
  ...Object.values(extensions),
  ...Object.values(names),
  ...Object.values(lightExtensions),
  ...Object.values(lightNames),
]);

const icons = {};
for (const icon of [...used].sort()) {
  const def = manifest.iconDefinitions[icon];
  if (def === undefined) throw new Error(`no icon definition for ${icon}`);
  const svg = readFileSync(join(root, "dist", def.iconPath), "utf8").trim();
  icons[icon] = svg;
}

/** Sorted record literal, one entry per line. */
function record(name, doc, entries) {
  const body = entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  return `/** ${doc} */\nexport const ${name}: Record<string, string> = {\n${body.join("\n")}\n};\n`;
}

const sorted = (map) => Object.entries(map).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const source = [
  `// Generated by scripts/generate-file-icons.mjs from material-icon-theme ${version}.`,
  "// Do not edit: run `npm run generate:icons` after upgrading the package.",
  "",
  record("ICON_SVG", "Icon name -> complete <svg> markup (colored, 16px viewBox).", sorted(icons)),
  record("EXTENSION_ICONS", 'Lowercase extension, may be compound ("css.ts") -> icon name.', sorted(extensions)),
  record("NAME_ICONS", "Lowercase exact file name -> icon name.", sorted(names)),
  record(
    "LIGHT_EXTENSION_ICONS",
    "Light-theme overrides of EXTENSION_ICONS (bright icons have darker variants).",
    sorted(lightExtensions),
  ),
  record("LIGHT_NAME_ICONS", "Light-theme overrides of NAME_ICONS.", sorted(lightNames)),
  `/** Icon used when no extension or name matches. */\nexport const DEFAULT_ICON = ${JSON.stringify(manifest.file)};\n`,
].join("\n");

writeFileSync(OUT, source);
console.log(
  `file-icons: ${Object.keys(icons).length} icons, ${Object.keys(extensions).length} extensions, ` +
    `${Object.keys(names).length} file names, ${Object.keys(lightExtensions).length}+` +
    `${Object.keys(lightNames).length} light overrides -> ${OUT}`,
);